/** Permisos de la aplicación: acceso a notificaciones y funciones opcionales del teléfono. */
@Composable
fun PermissionsScreen(onBack: () -> Unit) {
    val scrollBehavior = TopAppBarDefaults.exitUntilCollapsedScrollBehavior()
    Scaffold(
        modifier = Modifier.nestedScroll(scrollBehavior.nestedScrollConnection),
        topBar = {
            LargeFlexibleTopAppBar(
                title = { Text(stringResource(R.string.drawer_permissions), style = MaterialTheme.typography.displaySmallEmphasized) },
                subtitle = { Text(stringResource(R.string.permissions_subtitle)) },
                navigationIcon = {
                    IconButton(onClick = onBack) { Icon(Icons.AutoMirrored.Rounded.ArrowBack, contentDescription = stringResource(R.string.common_back)) }
                },
                scrollBehavior = scrollBehavior,
            )
        },
    ) { padding ->
        LazyColumn(
            modifier = Modifier.fillMaxSize(),
            contentPadding = PaddingValues(start = 16.dp, end = 16.dp, top = padding.calculateTopPadding() + 8.dp, bottom = padding.calculateBottomPadding() + 24.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            item { SectionTitle(stringResource(R.string.settings_access)) }
            item { NotificationAccessCard() }
            item { SectionTitle(stringResource(R.string.settings_phone_features)) }
            item { PhoneFeaturesCard() }
        }
    }
}
